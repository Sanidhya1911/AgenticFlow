"""Pydantic V2 models for LLM structured output and LangGraph agent handoffs.

These models define strict schemas that serve dual purposes:
1. System prompt guidance: Rich `Field(description=...)` annotations instruct
   LLMs (e.g. Llama 3.3 70B via Groq) during structured output / JSON tool-calling.
2. Deterministic handoffs: Strongly-typed data exchange across LangGraph agents
   (Planner, Executor, Corrector).
"""

from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, ConfigDict, Field, field_validator


class APIPayload(BaseModel):
    """Structured payload generated by the LLM (Planner or Corrector) to execute a REST API call."""

    model_config = ConfigDict(
        extra="ignore",
        populate_by_name=True,
    )

    endpoint: str = Field(
        ...,
        description=(
            "The exact target URI path to invoke, with all path variables replaced by concrete values "
            "(e.g., '/orders/123e4567-e89b-12d3-a456-426614174000'). Do NOT leave raw template placeholders "
            "like '{orderId}' or '{id}'."
        ),
        examples=["/orders/a1b2c3d4-e5f6-7890-abcd-ef1234567890", "/orders"],
    )

    method: str = Field(
        ...,
        description=(
            "The uppercase HTTP method verb to execute for this request. "
            "Must be one of: 'GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS', 'HEAD'."
        ),
        examples=["GET", "POST", "PUT", "DELETE"],
    )

    headers: Dict[str, str] = Field(
        default_factory=lambda: {"Content-Type": "application/json"},
        description=(
            "Key-value dictionary of HTTP request headers required for the call "
            "(e.g., {'Content-Type': 'application/json', 'Authorization': 'Bearer <token>'})."
        ),
    )

    json_body: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "The exact JSON payload to send in the request body, generated based on the OpenAPI schema "
            "and business constraints. For GET, DELETE, or requests without a body, provide an empty dictionary {}."
        ),
    )

    query_params: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Optional key-value pairs of URL query parameters to append to the endpoint "
            "(e.g., {'page': 1, 'limit': 20, 'status': 'completed'})."
        ),
    )

    @field_validator("method")
    @classmethod
    def normalize_method(cls, v: str) -> str:
        """Ensure HTTP method is uppercase and valid."""
        upper = v.strip().upper()
        allowed = {"GET", "POST", "PUT", "DELETE", "PATCH", "OPTIONS", "HEAD"}
        if upper not in allowed:
            raise ValueError(f"Invalid HTTP method '{v}'. Must be one of {allowed}")
        return upper


class APIResponse(BaseModel):
    """Structured representation of an executed HTTP test step captured by the Executor agent."""

    model_config = ConfigDict(extra="ignore")

    status_code: int = Field(
        ...,
        description=(
            "The numeric HTTP status code returned by the API server under test "
            "(e.g., 200, 201, 400, 401, 403, 404, 422, 500)."
        ),
        examples=[200, 201, 400, 404, 500],
    )

    response_data: Union[Dict[str, Any], List[Any], str] = Field(
        ...,
        description=(
            "The parsed response payload from the API server (as a dictionary or list for JSON responses, "
            "or as a string for text/HTML responses). Contains the server response body to be analyzed by the Corrector."
        ),
    )

    response_time_ms: float = Field(
        ...,
        description=(
            "The total round-trip latency of the HTTP request in milliseconds, measured from dispatch "
            "to response receipt."
        ),
        examples=[45.2, 120.8],
    )

    is_success: bool = Field(
        default=False,
        description="Convenience boolean flag indicating whether status_code is in the 2xx range (200-299).",
    )

    error_message: Optional[str] = Field(
        default=None,
        description=(
            "Diagnostic error message if the HTTP request encountered a network failure, connection timeout, "
            "or parsing error before a valid response could be received."
        ),
    )

    def model_post_init(self, __context: Any) -> None:
        """Automatically set is_success flag based on status_code."""
        if not self.is_success and 200 <= self.status_code < 300:
            self.is_success = True


class EndpointContext(BaseModel):
    """Contextual metadata extracted from OpenAPI specification provided to the LLM agent to plan and generate API test payloads."""

    model_config = ConfigDict(extra="ignore")

    endpoint_path: str = Field(
        ...,
        description=(
            "The standardized OpenAPI path template for the target endpoint, including parameterized path variables "
            "(e.g., '/orders/{orderId}' or '/categories')."
        ),
        examples=["/orders", "/orders/{orderId}"],
    )

    required_params: List[Dict[str, Any]] = Field(
        default_factory=list,
        description=(
            "List of required and optional parameters (path, query, header, cookie) with their names, locations ('path', 'query', etc.), "
            "data types, requirement flags, and descriptions extracted from the OpenAPI spec."
        ),
    )

    description: Optional[str] = Field(
        default="",
        description=(
            "The functional description and business summary of what this endpoint does, extracted directly "
            "from the OpenAPI specification summary and description fields."
        ),
    )

    method: Optional[str] = Field(
        default="GET",
        description="The HTTP method associated with this operation (e.g., 'GET', 'POST', 'PUT', 'DELETE').",
    )

    request_schema: Optional[Dict[str, Any]] = Field(
        default_factory=dict,
        description=(
            "Fully dereferenced and flattened JSON schema describing the expected request body structure, "
            "field names, data types, and validation constraints."
        ),
    )

    @classmethod
    def from_endpoint_operation(cls, op: Any) -> "EndpointContext":
        """Factory method to construct an EndpointContext directly from an EndpointOperation dataclass."""
        params_list = []
        for p in getattr(op, "parameters", []):
            params_list.append({
                "name": getattr(p, "name", ""),
                "in": getattr(p, "in_location", ""),
                "required": getattr(p, "required", False),
                "type": getattr(p, "schema_type", ""),
                "description": getattr(p, "description", ""),
                "details": getattr(p, "schema_details", {}),
            })

        req_body = getattr(op, "request_body", None)
        schema_dict = getattr(req_body, "schema_details", {}) if req_body else {}

        full_desc = []
        if getattr(op, "summary", None):
            full_desc.append(op.summary)
        if getattr(op, "description", None):
            full_desc.append(op.description)

        return cls(
            endpoint_path=getattr(op, "path", ""),
            method=getattr(op, "method", "GET"),
            required_params=params_list,
            description=" - ".join(full_desc) if full_desc else "",
            request_schema=schema_dict,
        )


# --- Supplementary Models for Deterministic LangGraph Agent Handoffs ---

class TestPlanStep(BaseModel):
    """A single deterministic test step formulated by the Planner agent."""

    __test__ = False  # Prevent pytest from treating this Pydantic model as a test case

    step_id: int = Field(
        ...,
        description="Sequential index of the test step in the execution chain (1-indexed).",
    )
    title: str = Field(
        ...,
        description="Concise descriptive title of what this test step validates (e.g., 'Create Order with Valid Items').",
    )
    context: EndpointContext = Field(
        ...,
        description="The OpenAPI endpoint context and constraints used to generate this test step.",
    )
    payload: APIPayload = Field(
        ...,
        description="The generated HTTP request payload to execute for this step.",
    )
    expected_status: int = Field(
        default=200,
        description="The expected HTTP status code for this test step (e.g., 200, 201, 400).",
    )


class CorrectionFeedback(BaseModel):
    """Diagnostic feedback formulated by the Corrector agent when an API request fails validation."""

    error_type: Literal["schema_mismatch", "http_error", "timeout", "auth_failure", "business_logic"] = Field(
        ...,
        description="Classification of the failure detected by the Corrector agent.",
    )
    diagnosis: str = Field(
        ...,
        description="Detailed natural-language diagnosis explaining why the request failed based on the response body and status.",
    )
    suggested_fix: str = Field(
        ...,
        description="Concrete instructions for how the payload or parameters should be modified to succeed.",
    )
    corrected_payload: Optional[APIPayload] = Field(
        default=None,
        description="If available, the immediate corrected APIPayload ready for re-execution.",
    )


class AgentHandoff(BaseModel):
    """State envelope passed across LangGraph nodes (Planner -> Executor -> Corrector)."""

    current_agent: Literal["planner", "executor", "corrector", "completed"] = Field(
        ...,
        description="The active agent role currently processing the state.",
    )
    step: Optional[TestPlanStep] = Field(
        default=None,
        description="The active test plan step being executed or evaluated.",
    )
    response: Optional[APIResponse] = Field(
        default=None,
        description="The execution result of the current step, populated by the Executor agent.",
    )
    feedback: Optional[CorrectionFeedback] = Field(
        default=None,
        description="Correction guidance populated by the Corrector agent if the test step failed.",
    )
    retry_count: int = Field(
        default=0,
        description="Number of automated correction retries attempted for the current step.",
    )
    max_retries: int = Field(
        default=3,
        description="Maximum retry threshold before terminating with a permanent test failure.",
    )
